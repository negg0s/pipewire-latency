"""Write and restore a PipeWire drop-in configuration."""

from __future__ import annotations

import os
import shutil
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

from .profiles import Profile

DEFAULT_RELATIVE = "pipewire/pipewire.conf.d/99-pipewire-latency.conf"


def default_config_path() -> Path:
    override = os.environ.get("PIPEWIRE_LATENCY_CONFIG")
    if override:
        return Path(override).expanduser()
    xdg = os.environ.get("XDG_CONFIG_HOME")
    base = Path(xdg).expanduser() if xdg else Path.home() / ".config"
    return base / DEFAULT_RELATIVE


def render_config(profile: Profile) -> str:
    return (
        "# Generated by pipewire-latency. Edit or remove this file to roll back.\n"
        "context.properties = {\n"
        f"    default.clock.rate = {profile.rate}\n"
        f"    default.clock.quantum = {profile.quantum}\n"
        f"    default.clock.min-quantum = {profile.min_quantum}\n"
        f"    default.clock.max-quantum = {profile.max_quantum}\n"
        "}\n"
    )


@dataclass(frozen=True)
class WriteResult:
    path: Path
    backup: Path | None
    content: str
    wrote: bool


def write_config(
    profile: Profile,
    path: Path | None = None,
    *,
    force: bool = False,
    dry_run: bool = False,
) -> WriteResult:
    target = path or default_config_path()
    content = render_config(profile)
    if dry_run:
        return WriteResult(path=target, backup=None, content=content, wrote=False)

    backup = None
    if target.exists():
        if not force:
            raise FileExistsError(
                f"{target} already exists. Re-run with --force to replace it."
            )
        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
        backup = target.with_name(f"{target.name}.{stamp}.bak")
        # Guard against two writes landing in the same microsecond.
        counter = 0
        while backup.exists():
            counter += 1
            backup = target.with_name(f"{target.name}.{stamp}.{counter}.bak")
        shutil.copy2(target, backup)

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")
    return WriteResult(path=target, backup=backup, content=content, wrote=True)


def list_backups(path: Path | None = None) -> list[Path]:
    target = path or default_config_path()
    return sorted(target.parent.glob(f"{target.name}.*.bak"))


def restore_config(path: Path | None = None) -> tuple[Path, Path | None]:
    """Restore the newest backup, or remove the file when no backup exists."""
    target = path or default_config_path()
    backups = list_backups(target)
    if backups:
        newest = backups[-1]
        shutil.copy2(newest, target)
        return target, newest
    if target.exists():
        target.unlink()
    return target, None
